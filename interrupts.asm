bits 32

section .text:

extern puts
extern putnum

global default_isr
global disk_read_isr
global disk_write_isr
global call_lidt

default_isr:
	pushad
	push byte 0x0F
	push error_string
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

disk_error:
	push byte 0x0F
	push disk_error_string
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

disk_read_isr:
	pushad

	mov edx, 0x1F7
	in al, dx
	test al, 0x01
	jnz disk_error
	test al, 0x08
	jz disk_error

	mov ecx, [disk_read_info + 0x4]
	mov edi, disk_read_info
	rep insw

	popad
	iret

disk_write_isr:
	pushad

	mov edx, 0x1F7
	in al, dx
	test al, 0x01
	jnz disk_error
	test al, 0x08
	jz disk_error

	mov ecx, [disk_write_info + 0x4]
	mov esi, disk_write_info
	rep outsw

	popad
	iret

call_lidt:
	mov long eax, [esp + 0x4]
	mov long [idt + 0x2], eax
	lidt [idt]
	ret 4
	
section .data:

disk_read_info:
	dd 0x0 ; buffer address
	dd 0x0 ; number of words (16 bit values) to read

disk_write_info:
	dd 0x0 ; buffer address
	dd 0x0 ; number of words to write

error_string db "interrupt generated by error", 0
disk_error_string db "disk controller interrupt contained error", 0

idt:
	dw 2047
	dd 0x0
