bits 32
%include "constants.asm"

section .text:

extern puts
extern putnum

global pic_init
global default_isr
global disk_isr
global prep_disk_isr
global call_lidt

pic_init:
	mov dx, 0x20
	mov al, 0x11
	out dx, al ; start initialization
	mov dx, 0xA0
	out dx, al

	mov dx, 0x21
	mov al, 0x20
	out dx, al ; set offsets
	mov dx, 0xA1
	mov al, 0x28
	out dx, al

	mov dx, 0x21
	mov al, 0x4
	out dx, al ; tell master where slave is
	mov dx, 0xA1
	mov al, 0x2
	out dx, al ; tell slave its cascade identity

	mov dx, 0x21
	mov al, 0x1
	out dx, al ; use 8086 mode
	mov dx, 0xA1
	out dx, al

	mov dx, 0x21
	mov al, 0xFB
	out dx, al ; unmasking only disk irqs because thats what ive written so far
	mov dx, 0xA1
	mov al, 0x3F
	out dx, al
	ret

default_isr:
	pushad
	mov ebx, [STAGE2_LOCATION]
	add ebx, error_string
	push byte 0x0F
	push ebx
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

disk_error:
	mov ebx, [STAGE2_LOCATION]
	add ebx, disk_error_string
	push byte 0x0F
	push ebx
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

slave_isr_end:
	; send end of interrupt command
	mov dx, 0x20
	mov al, 0x20
	out dx, al
	mov dx, 0xA0
	out dx, al

	popad
	iret

disk_isr:
	pushad

	mov edx, 0x1F7
	in al, dx
	test al, 0x01
	jnz disk_error
	test al, 0x08
	jz disk_error

	mov ebx, [STAGE2_LOCATION]
	mov al, [ebx + disk_info + 0x8]
	cmp al, 0x1
	je disk_read
	cmp al, 0x2
	je disk_write
	jmp disk_error

disk_read:
	mov ecx, [ebx + disk_info + 0x4]
	add ebx, disk_info
	mov edi, ebx
	rep insw
	jmp slave_isr_end

disk_write:
	mov ecx, [ebx + disk_info + 0x4]
	add ebx, disk_info
	mov esi, ebx
	rep outsw
	jmp slave_isr_end

prep_disk_isr:
	mov ebx, [STAGE2_LOCATION]
	mov eax, [esp + 0x4]
	mov [ebx + disk_info], eax
	mov eax, [esp + 0x8]
	mov [ebx + disk_info + 0x4], eax
	mov al, [esp + 0xC]
	mov [ebx + disk_info + 0x8], al
	ret 0xC

call_lidt:
	mov ebx, [STAGE2_LOCATION]
	mov long eax, [esp + 0x4]
	mov long [ebx + idt + 0x2], eax
	lidt [ebx + idt]
	ret 4
	
section .data:

disk_info:
	dd 0x0 ; buffer address
	dd 0x0 ; number of words (16 bit values) to read/write
	db 0x0 ; 1 for read, 2 for write

error_string db "interrupt generated by error", 0
disk_error_string db "disk controller interrupt contained error", 0

idt:
	dw 2047
	dd 0x0
