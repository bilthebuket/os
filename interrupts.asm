bits 32

section .text:

extern puts
extern putnum

global default_isr
global call_lidt

default_isr:
	cli
	hlt
	pushad
	push byte 0x0F
	push error_string
	push long 0x0
	push long 0x0
	call puts
	add esp, 0xD
	popad
	iret

call_lidt:
	mov long eax, [esp + 0x4]
	mov long [idt + 0x2], eax
	lidt [idt]
	ret
	
section .data:

error_string db "interrupt generated by error"
idt:
	dw 16383
	dd 0x0
