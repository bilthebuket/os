bits 32
%include "constants.asm"

section .text:

extern puts
extern putnum

global pic_init
global default_isr
global disk_isr
global slave_isr_handle_spurious
global prep_disk_isr
global call_lidt

pic_init:
	mov dx, 0x20
	mov al, 0x11
	out dx, al ; start initialization
	mov dx, 0xA0
	out dx, al

	mov dx, 0x21
	mov al, 0x20
	out dx, al ; set offsets
	mov dx, 0xA1
	mov al, 0x28
	out dx, al

	mov dx, 0x21
	mov al, 0x4
	out dx, al ; tell master where slave is
	mov dx, 0xA1
	mov al, 0x2
	out dx, al ; tell slave its cascade identity

	mov dx, 0x21
	mov al, 0x1
	out dx, al ; use 8086 mode
	mov dx, 0xA1
	out dx, al

	mov dx, 0x21
	mov al, 0xFB
	out dx, al ; unmasking only disk irqs because thats what ive written so far
	mov dx, 0xA1
	mov al, 0x3F
	out dx, al
	ret

default_isr:
	pushad
	mov ebx, [STAGE2_LOCATION]
	add ebx, interrupt_error_string
	push byte 0x0F
	push ebx
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

disk_error:
	mov ebx, [STAGE2_LOCATION]
	add ebx, disk_interrupt_error_string
	push long 0x0F
	push ebx
	push long 0x0
	push long 0x0
	call puts
	popad
	iret

slave_isr_end:
	; send end of interrupt command
	mov dx, 0xA0
	mov al, 0x20
	out dx, al
	mov dx, 0x20
	out dx, al

	popad
	iret

slave_isr_handle_spurious:
	pushad

	mov dx, 0x0B
	mov al, 0xA0
	out dx, al
	in al, dx
	test al, 0x80
	jz is_spurious

	jmp disk_error ; a secondary ata channel interrupt was generated which isnt supposed to happen

is_spurious: ; send eoi to the master but not the slave
	mov al, 0x20
	mov dx, 0x20
	out dx, al
	popad
	iret

disk_isr:
	pushad

	mov edx, 0x1F7
	in al, dx
	test al, 0x01
	jnz disk_error
	test al, 0x08
	jz slave_isr_end ; do nothing if controller isnt ready for read/write

	mov ebx, [STAGE2_LOCATION]
	mov eax, [disk_func_addr + ebx]
	cmp eax, 0x0
	je disk_error
	call eax
	jmp slave_isr_end

prep_disk_isr:
	mov ebx, [STAGE2_LOCATION]
	mov eax, [esp + 0x4]
	mov [ebx + disk_func_addr], eax
	ret 0x4

call_lidt:
	mov ebx, [STAGE2_LOCATION]
	mov long eax, [esp + 0x4]
	mov long [ebx + idt + 0x2], eax
	lidt [ebx + idt]
	ret 4
	
section .data:

disk_func_addr:
	dd 0x0 ; address of the function to call on disk interrupt (disk_write/disk_read)

interrupt_error_string db "interrupt generated by error", 0
disk_interrupt_error_string db "disk controller interrupt contained error", 0

idt:
	dw 2047
	dd 0x0
